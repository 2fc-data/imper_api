interface Linha {
  nome: string;
  patrimonio: string;
}

function parseLista(raw: string): Linha[] {
  return raw
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l.length > 0 && !l.startsWith('EQUIPAMENTO'))
    .map((l) => {
      const parts = l.split('\t');
      if (parts.length < 2) return null;
      return { nome: parts[0].trim(), patrimonio: parts[1].trim() };
    })
    .filter((x): x is Linha => x !== null);
}

async function main() {
  const dryRun = process.argv.includes('--dry-run');
  const linhas = parseLista(LISTA);
  console.log(`Total de linhas na lista: ${linhas.length}`);

  // Status e unidade
  const status = await p.statusEquipamento.findFirst({ where: { nome: 'DISPONÍVEL' } });
  if (!status) throw new Error('Status DISPONÍVEL não encontrado');
  const um = await p.unidadeMedida.upsert({
    where: { nome: 'UNIDADE' },
    create: { nome: 'UNIDADE' },
    update: {},
  });

  // Carrega equipamentos existentes
  const existentes = await p.equipamento.findMany({
    select: { id: true, codigo: true, descricao: true, numeroPatrimonio: true },
    orderBy: { codigo: 'asc' },
  });

  // Map: normalize(descricao) → fila de equipamentos sem patrimônio
  const mapa = new Map<string, typeof existentes>();
  for (const e of existentes) {
    if (e.numeroPatrimonio) continue;
    const k = normalize(e.descricao);
    if (!mapa.has(k)) mapa.set(k, []);
    mapa.get(k)!.push(e);
  }

  // Próximo código
  let maxNum = 0;
  for (const e of existentes) {
    const m = e.codigo.match(/^EQP-(\d+)$/);
    if (m) maxNum = Math.max(maxNum, parseInt(m[1], 10));
  }
  let proximo = maxNum + 1;

  let atualizados = 0;
  let criados = 0;
  const naoEncontrados: string[] = [];

  for (const { nome, patrimonio } of linhas) {
    const k = normalize(nome);
    const fila = mapa.get(k);

    if (fila && fila.length > 0) {
      const eqp = fila.shift()!;
      if (!dryRun) {
        await p.equipamento.update({
          where: { id: eqp.id },
          data: { numeroPatrimonio: patrimonio },
        });
      }
      atualizados++;
    } else {
      const codigo = `EQP-${String(proximo).padStart(3, '0')}`;
      if (!dryRun) {
        await p.equipamento.create({
          data: {
            codigo,
            descricao: nome,
            numeroPatrimonio: patrimonio,
            statusId: status.id,
            unidadeMedidaId: um.id,
          },
        });
      }
      proximo++;
      criados++;
    }
  }

  console.log(`\n=== Resultado${dryRun ? ' (DRY-RUN)' : ''} ===`);
  console.log(`Atualizados (patrimônio preenchido): ${atualizados}`);
  console.log(`Criados (novo EQP-*):               ${criados}`);
  console.log(`Total processado:                    ${linhas.length}`);

  // Equipamentos sem patrimônio após importação
  const restantes = await p.equipamento.count({
    where: { numeroPatrimonio: null },
  });
  console.log(`Equipamentos ainda sem patrimônio:  ${restantes}`);
}

main()
